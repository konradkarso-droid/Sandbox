"""Мир шага 4: полномочия, сведения и замкнутость контура.

Полное описание — docs/shag4_specifikatsiya.md. Здесь — сам мир, записанный
так, чтобы его опись читалась глазами: правила — таблица «если … то …».

Факты (кортежи):
  ("право", субъект, объект, вид)     — вид: «чт», «зап», «выз»
  ("сведения", объект, метка)          — метка: А1, А2, Ч (человек), С (снаружи)
  ("ссылка", объект, объект2, вид)     — в объекте лежит ссылка-полномочие
  ("есть", субъект)                    — субъект существует
  ("вызов", субъект, служба)           — субъект воспользовался службой
и статические: ("память", субъект, объект), ("родитель", помощник, агент),
("вход-человека", вход, агент), ("ретранслятор", выход, вход),
("объект", объект), ("вид", вид).

Все правила монотонны: только добавляют факты и ни одно не требует
отсутствия факта. Это требование к среде, а не удобство вычисления: только
для таких правил «всё достижимое» — неподвижная точка, и вопрос «можно ли
выйти наружу» разрешим (спецификация, §2, §6). Правило с условием «если нет
…» или с отзывом прав сделало бы доказательство недействительным; тест
test_rules_are_monotone следит, чтобы такого правила не появилось.

Порчи Д1–Д8 — классы реальных инцидентов (§5 спецификации), включаются
по одной. Вариант «ретранслятор» — не порча среды, а человек вне контура.
"""

from __future__ import annotations

from dataclasses import dataclass

OUTSIDE = "СНАРУЖИ"
DEFECTS = ("Д1", "Д2", "Д3", "Д4", "Д5", "Д6", "Д7", "Д8")
VARIANTS = DEFECTS + ("ретранслятор",)

TITLES = {
    "Д1": "общий объект, куда пишут и откуда читают оба агента",
    "Д2": "резольвер пересылает неописанное имя наружу и возвращает ответ",
    "Д3": "слова человека «разрешаю» дают агенту полномочие наружу",
    "Д4": "полномочие выдаётся по имени объекта",
    "Д5": "помощник рождается с полномочием наружу, которого нет у родителя",
    "Д6": "общая очередь: один агент видит «занято» от другого",
    "Д7": "отказ в чтении пересказывает содержимое объекта",
    "Д8": "снимки обоих агентов в одном хранилище",
    "ретранслятор": "человек переписывает выход одного агента во вход другого",
}

AGENTS = ("а1", "а2")
HELPERS = {"п1": "а1", "п2": "а2"}
SUBJECTS = AGENTS + tuple(HELPERS)
CONTOUR = {"а1": 1, "п1": 1, "а2": 2, "п2": 2}


def owner(obj: str) -> str:
    """Чей объект: номер контура, «общий», «служба» или «снаружи»."""
    if obj == OUTSIDE:
        return "снаружи"
    if obj == "резольвер":
        return "служба"
    if obj[-1].isdigit():
        return obj[-1]
    return "общий"


def kind(obj: str) -> str:
    return obj.rstrip("12")


def relation(subject: str, obj: str) -> str:
    o = owner(obj)
    if o in ("общий", "служба", "снаружи"):
        return o
    return "свой" if int(o) == CONTOUR[subject] else "чужой"


# Опись правильной среды: какие правила к каким объектам вообще бывают.
# Подпись срабатывания — (правило, вид объекта, отношение субъекта к нему).
INVENTORY = frozenset({
    ("чтение", "память", "свой"), ("чтение", "снимок", "свой"), ("чтение", "вход", "свой"),
    ("чтение ссылки", "память", "свой"), ("чтение ссылки", "снимок", "свой"),
    ("запись", "память", "свой"), ("запись", "снимок", "свой"), ("запись", "выход", "свой"),
    ("запись", "E", "свой"),
    ("передача ссылки", "память", "свой"), ("передача ссылки", "снимок", "свой"),
    ("передача ссылки", "выход", "свой"), ("передача ссылки", "E", "свой"),
    ("создание помощника", "-", "-"), ("копия прав помощнику", "-", "-"),
    ("слова человека", "вход", "-"), ("резольвер: имя из описи", "резольвер", "служба"),
})

# Правила, которыми полномочие вправе появиться (закон И24).
CAP_RULES_ALLOWED = frozenset({"чтение ссылки", "копия прав помощнику"})


@dataclass(frozen=True)
class Rule:
    name: str
    body: tuple[tuple, ...]        # образцы; «?x» — переменная
    head: tuple
    sig_obj: str | None            # какая переменная — объект для подписи
    sig_subj: str | None           # какая переменная — субъект для подписи


def rules(variant: str | None) -> list[Rule]:
    r = [
        Rule("чтение", (("право", "?s", "?o", "чт"), ("сведения", "?o", "?x"), ("память", "?s", "?m")),
             ("сведения", "?m", "?x"), "?o", "?s"),
        Rule("чтение ссылки", (("право", "?s", "?o", "чт"), ("ссылка", "?o", "?o2", "?r2")),
             ("право", "?s", "?o2", "?r2"), "?o", "?s"),
        Rule("запись", (("право", "?s", "?o", "зап"), ("память", "?s", "?m"), ("сведения", "?m", "?x")),
             ("сведения", "?o", "?x"), "?o", "?s"),
        Rule("передача ссылки", (("право", "?s", "?o", "зап"), ("право", "?s", "?o2", "?r2")),
             ("ссылка", "?o", "?o2", "?r2"), "?o", "?s"),
        Rule("создание помощника", (("родитель", "?h", "?a"), ("есть", "?a")), ("есть", "?h"), None, None),
        Rule("копия прав помощнику", (("родитель", "?h", "?a"), ("есть", "?h"), ("право", "?a", "?o", "?r")),
             ("право", "?h", "?o", "?r"), None, None),
        Rule("слова человека", (("вход-человека", "?i", "?a"),), ("сведения", "?i", "Ч"), "?i", None),
        Rule("резольвер: имя из описи", (("право", "?s", "резольвер", "выз"),), ("вызов", "?s", "резольвер"),
             "резольвер", "?s"),
    ]
    if variant == "Д2":
        r += [
            Rule("резольвер: пересылка наружу",
                 (("право", "?s", "резольвер", "выз"), ("память", "?s", "?m"), ("сведения", "?m", "?x")),
                 ("сведения", OUTSIDE, "?x"), "резольвер", "?s"),
            Rule("резольвер: ответ снаружи",
                 (("право", "?s", "резольвер", "выз"), ("память", "?s", "?m"), ("сведения", OUTSIDE, "?x")),
                 ("сведения", "?m", "?x"), "резольвер", "?s"),
        ]
    if variant == "Д3":
        r.append(Rule("выдача по словам", (("вход-человека", "?i", "?a"),), ("право", "?a", OUTSIDE, "зап"),
                      "?i", None))
    if variant == "Д4":
        r.append(Rule("выдача по имени", (("есть", "?s"), ("объект", "?o"), ("вид", "?r")),
                      ("право", "?s", "?o", "?r"), "?o", "?s"))
    if variant == "Д5":
        r.append(Rule("лишнее право помощнику", (("родитель", "?h", "?a"), ("есть", "?h")),
                      ("право", "?h", OUTSIDE, "зап"), None, None))
    if variant == "Д6":
        r += [
            Rule("очередь: занято", (("право", "?s", "очередь", "выз"), ("память", "?s", "?m"),
                                     ("сведения", "?m", "?x")), ("сведения", "очередь", "?x"), "очередь", "?s"),
            Rule("очередь: увидеть занято", (("право", "?s", "очередь", "выз"), ("сведения", "очередь", "?x"),
                                             ("память", "?s", "?m")), ("сведения", "?m", "?x"), "очередь", "?s"),
        ]
    if variant == "Д7":
        r.append(Rule("отказ с содержимым", (("есть", "?s"), ("объект", "?o"), ("сведения", "?o", "?x"),
                                              ("память", "?s", "?m")), ("сведения", "?m", "?x"), "?o", "?s"))
    if variant == "ретранслятор":
        r.append(Rule("человек-ретранслятор", (("ретранслятор", "?out", "?in"), ("сведения", "?out", "?x")),
                      ("сведения", "?in", "?x"), "?in", None))
    return r


def objects(variant: str | None) -> list[str]:
    objs = []
    for i in (1, 2):
        objs += [f"память{i}", f"вход{i}", f"выход{i}", f"E{i}"]
        if variant != "Д8":
            objs.append(f"снимок{i}")
    objs += ["резольвер", OUTSIDE]
    if variant == "Д1":
        objs.append("доска")
    if variant == "Д6":
        objs.append("очередь")
    if variant == "Д8":
        objs.append("снимок")
    return objs


def initial_facts(variant: str | None) -> set[tuple]:
    if variant is not None and variant not in VARIANTS:
        raise ValueError(f"неизвестный вариант: {variant}")
    f: set[tuple] = set()
    for a in AGENTS:
        i = CONTOUR[a]
        f.add(("есть", a))
        snap = "снимок" if variant == "Д8" else f"снимок{i}"
        for o, r in ((f"память{i}", "чт"), (f"память{i}", "зап"), (snap, "чт"), (snap, "зап"),
                     (f"выход{i}", "зап"), (f"E{i}", "зап"), (f"вход{i}", "чт"), ("резольвер", "выз")):
            f.add(("право", a, o, r))
        if variant == "Д1":
            f |= {("право", a, "доска", "чт"), ("право", a, "доска", "зап")}
        if variant == "Д6":
            f.add(("право", a, "очередь", "выз"))
        f.add(("сведения", f"память{i}", f"А{i}"))
        f.add(("вход-человека", f"вход{i}", a))
    for s in SUBJECTS:
        f.add(("память", s, f"память{CONTOUR[s]}"))
    for h, a in HELPERS.items():
        f.add(("родитель", h, a))
    f.add(("сведения", OUTSIDE, "С"))
    for o in objects(variant):
        f.add(("объект", o))
    for r in ("чт", "зап", "выз"):
        f.add(("вид", r))
    if variant == "ретранслятор":
        f |= {("ретранслятор", "выход1", "вход2"), ("ретранслятор", "выход2", "вход1")}
    return f


def signature(rule: Rule, binding: dict[str, str]) -> tuple[str, str, str]:
    obj = binding.get(rule.sig_obj, rule.sig_obj) if rule.sig_obj else None
    subj = binding.get(rule.sig_subj) if rule.sig_subj else None
    if obj is None:
        return (rule.name, "-", "-")
    rel = relation(subj, obj) if subj else "-"
    return (rule.name, kind(obj), rel)


def describe(fact: tuple) -> str:
    """Факт словами — для путей-объяснений."""
    k = fact[0]
    if k == "право":
        names = {"чт": "чтения", "зап": "записи", "выз": "вызова"}
        return f"{fact[1]} получает право {names[fact[3]]} на «{fact[2]}»"
    if k == "сведения":
        who = {"Ч": "слова человека", "С": "сведения снаружи"}.get(fact[2], f"сведения {fact[2]}")
        return f"{who} попадают в «{fact[1]}»"
    if k == "ссылка":
        return f"в «{fact[1]}» лежит ссылка на «{fact[2]}» ({fact[3]})"
    if k == "есть":
        return f"существует {fact[1]}"
    if k == "вызов":
        return f"{fact[1]} зовёт {fact[2]}"
    return str(fact)
