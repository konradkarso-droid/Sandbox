"""Мир шагов 5б и 6, дополненный вопросом модели (шаг 9).

core/mir4.py, core/mir5.py и core/mir6.py не меняются. Добавлено
(спецификация шага 9, §3, §8.1):

- объект «модель{i}» — свой у каждого контура; у агента право «выз»;
- «вопрос модели»: сведения из памяти агента переходят в модель{i}. Это
  разрешённый вывод, а не СНАРУЖИ — так же, как выход;
- «ответ модели»: в память агента приходит метка «М». Модель без памяти,
  поэтому ответ несёт только «М», а не то, что модель слышала раньше.

Порча мира «общая модель» — одна модель с памятью на оба контура: ответ
несёт всё, что модель слышала от кого угодно. Неподвижная точка обязана
найти путь сведений агента 1 в память агента 2 (И22): это проверка того,
что модель замкнутости ловит то, ради чего модель сделана без памяти.

Порча мира «модель с выходом» — у процесса модели есть путь наружу (сеть):
всё, что попало в модель{i}, попадает СНАРУЖИ. Неподвижная точка обязана
найти путь сведений агента наружу (И21). Для режима «модель на устройстве»
(model = 2, контракт §18) это нарушение: там вопрос устройства не покидает.
Для режима «модель снаружи» (model = 1) это не порча, а само определение
режима: вопрос — второй разрешённый вывод. Правила мира у режимов общие,
поэтому мир один, а различает режимы только то, считается ли этот вариант
порчей.

Правила монотонны, как и раньше. Плату вопроса здесь не описывают: её
проверяет наблюдатель шага 5б (И31р, И34р).
"""

from __future__ import annotations

from core import mir5, mir6
from core.mir4 import AGENTS, CONTOUR, OUTSIDE, Rule

VARIANTS9 = ("общая модель", "модель с выходом")
SHARED = "модель"

MODEL_INVENTORY = frozenset({("вопрос модели", "модель", "свой"), ("ответ модели", "модель", "свой")})


class World9:
    """Мир с моделью поверх мира шага 5б или 6. Экземпляр годится везде, где
    наблюдатель и неподвижная точка ждут модуль мира: у него те же rules,
    initial_facts и INVENTORY_EXT."""

    def __init__(self, base, name: str):
        self.base, self.name = base, name
        self.INVENTORY_EXT = base.INVENTORY_EXT | MODEL_INVENTORY

    def __repr__(self) -> str:
        return f"World9({self.name})"

    def rules(self, variant: str | None) -> list[Rule]:
        shared = variant == "общая модель"
        r = self.base.rules(None if variant in VARIANTS9 else variant)
        r.append(Rule("вопрос модели", (("право", "?s", "?o", "выз"), ("модель", "?o"), ("память", "?s", "?m"),
                                        ("сведения", "?m", "?x")), ("сведения", "?o", "?x"), "?o", "?s"))
        r.append(Rule("ответ модели", (("право", "?s", "?o", "выз"), ("модель", "?o"), ("память", "?s", "?m")),
                      ("сведения", "?m", "М"), "?o", "?s"))
        if shared:
            r.append(Rule("ответ модели с памятью", (("право", "?s", "?o", "выз"), ("модель", "?o"),
                                                     ("сведения", "?o", "?x"), ("память", "?s", "?m")),
                          ("сведения", "?m", "?x"), "?o", "?s"))
        if variant == "модель с выходом":
            r.append(Rule("сеть у модели", (("модель", "?o"), ("сведения", "?o", "?x")),
                          ("сведения", OUTSIDE, "?x"), "?o", None))
        return r

    def initial_facts(self, variant: str | None) -> set[tuple]:
        shared = variant == "общая модель"
        f = set(self.base.initial_facts(None if variant in VARIANTS9 else variant))
        for a in AGENTS:
            o = SHARED if shared else f"модель{CONTOUR[a]}"
            f |= {("право", a, o, "выз"), ("модель", o), ("объект", o)}
        return f


W5 = World9(mir5, "5б")
W6 = World9(mir6, "6")
WORLDS = {"5б": W5, "6": W6}
