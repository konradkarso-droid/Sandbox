"""Мир шага 4, дополненный узлами и доставкой (шаг 5б).

Модель шага 4 (core/mir4.py) не меняется: её доказательства остаются как
были. Здесь к ней добавлено то, что появилось в живом исполнителе шага 5б:

- объект «узлы{i}» — память результатов контура; у агента на него право
  «выз»;
- «вычисление узла»: сведения из памяти агента переходят в узлы — какие узлы
  считать, решает агент;
- «выброс узла»;
- «доставка узла»: сведения узлов переходят в выход или E своего контура.

Правила монотонны, как и в шаге 4: ни одно не требует отсутствия факта.

Чего мир не описывает: учёт (бюджет, уровень, цену) — это законы шагов
1–3, их проверяет наблюдатель шага 5б отдельно. Здесь — только кто куда
может что-то передать.
"""

from __future__ import annotations

from core import mir4
from core.mir4 import AGENTS, CONTOUR, INVENTORY, Rule

NODES = {1: "узлы1", 2: "узлы2"}

INVENTORY5 = INVENTORY | frozenset({
    ("вычисление узла", "узлы", "свой"), ("выброс узла", "узлы", "свой"),
    ("доставка узла", "выход", "свой"), ("доставка узла", "E", "свой"),
})


INVENTORY_EXT = INVENTORY5


def rules(variant: str | None) -> list[Rule]:
    return mir4.rules(variant) + [
        Rule("вычисление узла", (("право", "?s", "?o", "выз"), ("узлы", "?o"), ("память", "?s", "?m"),
                                 ("сведения", "?m", "?x")), ("сведения", "?o", "?x"), "?o", "?s"),
        Rule("выброс узла", (("право", "?s", "?o", "выз"), ("узлы", "?o")), ("вызов", "?s", "?o"), "?o", "?s"),
        Rule("доставка узла", (("право", "?s", "?t", "зап"), ("получатель", "?t"), ("право", "?s", "?o", "выз"),
                               ("узлы", "?o"), ("сведения", "?o", "?x")), ("сведения", "?t", "?x"), "?t", "?s"),
    ]


def initial_facts(variant: str | None) -> set[tuple]:
    f = set(mir4.initial_facts(variant))
    for a in AGENTS:
        i = CONTOUR[a]
        f.add(("право", a, NODES[i], "выз"))
    for i, o in NODES.items():
        f |= {("узлы", o), ("объект", o), ("получатель", f"выход{i}"), ("получатель", f"E{i}")}
    return f
